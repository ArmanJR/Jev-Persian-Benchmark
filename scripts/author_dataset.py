def compile_cases(cases, prefix, paired=()):
    scenarios, gold = [], []
    rotation, counts = {}, Counter({i: 0 for i in range(4)})
    for a, b, j, _kind in paired:
        ga, gb = cases[a]["questions"][j]["expected"], cases[b]["questions"][j]["expected"]
        r = min(
            range(4),
            key=lambda r: sum(
                (counts[k] + ((ga - r) % 4 == k) + ((gb - r) % 4 == k)) ** 2 for k in range(4)
            ),
        )
        rotation[a, j] = rotation[b, j] = r
        counts[(ga - r) % 4] += 1
        counts[(gb - r) % 4] += 1
    seen_categories = set()
    for i, src in enumerate(cases):
        sid = f"{prefix}{i + 1:03d}"
        scenario = {k: v for k, v in src.items() if k != "questions"}
        scenario.update(id=sid, questions=[])
        first = src["category"] not in seen_categories and prefix == "s"
        seen_categories.add(src["category"])
        en = ENGLISH.get(src["category"], []) if first else []
        en_by_j = dict(zip([0, 1, 2, 3, 5], en, strict=False))
        for j, source_q in enumerate(src["questions"]):
            qid = f"{sid}q{j + 1}"
            q = {k: v for k, v in source_q.items() if k not in {"expected", "rationale"}}
            q["id"] = qid
            expected = source_q["expected"]
            english = None
            if j in en_by_j:
                prompt, crit = en_by_j[j]
                english = {"type": q["type"], "instructions": prompt}
                if crit is not None:
                    english["criteria"] = crit.split("|")
            if q["type"] == "choice":
                if (i, j) in rotation:
                    r = rotation[i, j]
                else:
                    target = min(counts, key=lambda k: (counts[k], k))
                    r = (expected - target) % 4
                    counts[target] += 1
                opts = q["criteria"][r:] + q["criteria"][:r]
                q["criteria"] = dict(zip("ABCD", opts, strict=True))
                expected = "ABCD"[(expected - r) % 4]
                if english:
                    opts = english["criteria"][r:] + english["criteria"][:r]
                    english["criteria"] = dict(zip("ABCD", opts, strict=True))
            if english:
                q["english"] = english
            scenario["questions"].append(q)
            gold.append({"id": qid, "expected": expected, "rationale": source_q["rationale"]})
        scenarios.append(scenario)
    pairs = [
        {
            "id": f"p{k + 1:02d}",
            "kind": kind,
            "questions": [f"{prefix}{a + 1:03d}q{j + 1}", f"{prefix}{b + 1:03d}q{j + 1}"],
        }
        for k, (a, b, j, kind) in enumerate(paired)
    ]
    return scenarios, gold, pairs


def write_jsonl(path, rows):
    path.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )


