"""Authoritative, manually authored v1 cases; emit JSONL without normalizing text.

Run from the repository root with uv run --no-project scripts/author_dataset.py.
The helpers expand explicit cases and rotate options; they never generate text or labels.
"""

import hashlib
import json
from collections import Counter
from pathlib import Path

CASES = []
PAIRS = []


def C(prompt, options, gold, reason):
    return {
        "type": "choice",
        "instructions": prompt,
        "criteria": options.split("|"),
        "expected": gold,
        "rationale": reason,
    }


def N(prompt, gold, reason):
    return {"type": "noul", "instructions": prompt, "expected": gold, "rationale": reason}


def S(prompt, levels, gold, reason):
    return {
        "type": "score",
        "instructions": prompt,
        "criteria": levels.split("|"),
        "expected": gold,
        "rationale": reason,
    }


def case(category, text, tags, questions):
    assert len(questions) == 6
    CASES.append(
        {
            "category": category,
            "state": {"text": text},
            "tags": tags.split(),
            "questions": questions,
        }
    )


def pair(category, kind, texts, tags, choices, nouls, scores):
    start = len(CASES)
    for i in range(2):
        qs = [C(p, opts, gs[i], rs[i]) for p, opts, gs, rs in choices]
        qs += nouls[i] + [scores[i]]
        case(category, texts[i], tags[i], qs)
    for j in range(3):
        PAIRS.append((start, start + 1, j, kind))


